export const PRODUCTS: readonly Product[] = Object.freeze(
  SEED_PRODUCTS.map((p) => Object.freeze({ ...p, availability: availabilityFor(p.stock) })),
);

const PRODUCTS_BY_ID = new Map(PRODUCTS.map((p) => [p.id, p]));

/** Synchronous catalogue lookup used by services. IDs are matched case-insensitively. */
export function findProductById(id: string): Product | undefined {
  return PRODUCTS_BY_ID.get(id.trim().toUpperCase());
}
